from fastapi import APIRouter, Depends
from app.schemas.suggestion import SuggestionRequest, SuggestionResponse, ErrorResponse
from app.services.groq_service import GroqService, get_groq_service

router = APIRouter(prefix="/api", tags=["Username Suggestions"])

@router.post(
    "/suggest-username",
    response_model=SuggestionResponse,
    summary="Generate 3 AI-suggested usernames based on interests",
    description="Takes a list of user interests and returns exactly three creative, distinct username suggestions generated by Groq LLM.",
    responses={
        400: {"model": ErrorResponse, "description": "Validation Error (empty interests list or invalid item)"},
        429: {"description": "Groq API rate limit exceeded"},
        503: {"description": "GROQ_API_KEY not configured on the microservice"},
        504: {"description": "Upstream AI service timeout"},
    },
)
def suggest_username(
    payload: SuggestionRequest,
    service: GroqService = Depends(get_groq_service)
) -> SuggestionResponse:
    suggestions = service.generate_suggestions(payload.interests)
    return SuggestionResponse(suggestions=suggestions)
